#!/usr/bin/env bash
# T-32 (6), T-32 (8)
set -euo pipefail

psql -v ON_ERROR_STOP=1 --username "$POSTGRES_USER" --dbname postgres \
    -v db="$ONE_DB_NAME" \
    -v owner_password="$ONE_OWNER_PASSWORD" \
    -v app_password="$ONE_APP_PASSWORD" <<'SQL'
CREATE ROLE one_owner LOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION NOBYPASSRLS
    PASSWORD :'owner_password';
CREATE ROLE one_app LOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION NOBYPASSRLS
    PASSWORD :'app_password';

CREATE DATABASE :"db" OWNER one_owner;
REVOKE ALL ON DATABASE :"db" FROM PUBLIC;
GRANT CONNECT, TEMPORARY ON DATABASE :"db" TO one_app;
SQL

psql -v ON_ERROR_STOP=1 --username "$POSTGRES_USER" --dbname "$ONE_DB_NAME" <<'SQL'
CREATE EXTENSION IF NOT EXISTS vector;

REVOKE ALL ON SCHEMA public FROM PUBLIC;
GRANT USAGE ON SCHEMA public TO one_app;

ALTER DEFAULT PRIVILEGES FOR ROLE one_owner
    GRANT USAGE ON SCHEMAS TO one_app;
ALTER DEFAULT PRIVILEGES FOR ROLE one_owner
    GRANT SELECT, INSERT, UPDATE ON TABLES TO one_app;
ALTER DEFAULT PRIVILEGES FOR ROLE one_owner
    GRANT USAGE, SELECT ON SEQUENCES TO one_app;
ALTER DEFAULT PRIVILEGES FOR ROLE one_owner
    REVOKE EXECUTE ON FUNCTIONS FROM PUBLIC;
ALTER DEFAULT PRIVILEGES FOR ROLE one_owner
    GRANT EXECUTE ON FUNCTIONS TO one_app;
SQL
