//! `security-design`: the published plain-metadata list of the security design is generated in Turkish and English from `conformance/store/plain-columns.toml` and the committed pages equal what the list generates (SEC-30, T-32 (4), OP-5).

use std::fmt::Write as _;
use std::path::Path;

use serde::Deserialize;

use super::plain_columns::LIST;
use super::{read_opt, v};
use crate::Violation;
use crate::rules::files::read;

/// The generated pages, one per language.
pub(crate) const PAGES: [(Lang, &str); 2] = [
    (Lang::En, "security/plain-metadata.en.md"),
    (Lang::Tr, "security/plain-metadata.tr.md"),
];

/// A published language.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(crate) enum Lang {
    En,
    Tr,
}

#[derive(Debug, Deserialize)]
struct Source {
    encrypted_type: String,
    #[serde(default)]
    column: Vec<Column>,
    #[serde(default)]
    encrypted_only: Vec<Named>,
    #[serde(default)]
    known_leak: Vec<Entry>,
    #[serde(default)]
    rule: Vec<Entry>,
}

#[derive(Debug, Deserialize)]
struct Column {
    name: String,
    sql_type: String,
    kind: String,
    basis: String,
    meaning: String,
    #[serde(default)]
    meaning_tr: String,
    #[serde(default)]
    values: Option<Vec<String>>,
}

#[derive(Debug, Deserialize)]
struct Named {
    name: String,
    basis: String,
}

#[derive(Debug, Deserialize)]
struct Entry {
    #[serde(default)]
    name: String,
    #[serde(default)]
    id: String,
    #[serde(default)]
    basis: String,
    meaning: String,
    #[serde(default)]
    meaning_tr: String,
}

struct Words {
    title: &'static str,
    intro: &'static str,
    encrypted: &'static str,
    head: &'static str,
    never: &'static str,
    never_intro: &'static str,
    never_head: &'static str,
    leaks: &'static str,
    rules: &'static str,
}

const EN: Words = Words {
    title: "Plain metadata",
    intro: "These are the only columns One stores without encryption. Every other column holds ciphertext under the person's keys.",
    encrypted: "Encrypted column type",
    head: "| Column | SQL type | Kind | Values | Basis | Meaning |",
    never: "Never a column",
    never_intro: "These names live only inside the ciphertext.",
    never_head: "| Name | Basis |",
    leaks: "What the plain metadata still shows",
    rules: "Rules",
};

const TR: Words = Words {
    title: "Düz üst veri",
    intro: "One'ın şifresiz sakladığı sütunlar yalnız bunlardır. Diğer her sütun kişinin anahtarlarıyla şifreli metin tutar.",
    encrypted: "Şifreli sütun türü",
    head: "| Sütun | SQL türü | Tür | Değerler | Dayanak | Anlamı |",
    never: "Hiçbir zaman sütun olmayanlar",
    never_intro: "Bu adlar yalnız şifreli metnin içinde yaşar.",
    never_head: "| Ad | Dayanak |",
    leaks: "Düz üst verinin yine de gösterdikleri",
    rules: "Kurallar",
};

fn meaning<'a>(lang: Lang, en: &'a str, tr: &'a str) -> &'a str {
    match lang {
        Lang::En => en,
        Lang::Tr => tr,
    }
}

fn render(source: &Source, lang: Lang) -> String {
    let w = match lang {
        Lang::En => &EN,
        Lang::Tr => &TR,
    };
    let mut out = format!(
        "<!-- Generated by `cargo xtask security-design` from {LIST}. -->\n\n# {}\n\n{}\n\n{}: `{}`\n\n{}\n|---|---|---|---|---|---|\n",
        w.title, w.intro, w.encrypted, source.encrypted_type, w.head
    );
    for c in &source.column {
        let values = c
            .values
            .as_ref()
            .map(|v| {
                v.iter()
                    .map(|x| format!("`{x}`"))
                    .collect::<Vec<_>>()
                    .join(", ")
            })
            .unwrap_or_default();
        let _ = writeln!(
            out,
            "| `{}` | `{}` | {} | {} | {} | {} |",
            c.name,
            c.sql_type,
            c.kind,
            values,
            c.basis,
            meaning(lang, &c.meaning, &c.meaning_tr)
        );
    }
    let _ = writeln!(
        out,
        "\n## {}\n\n{}\n\n{}\n|---|---|",
        w.never, w.never_intro, w.never_head
    );
    for n in &source.encrypted_only {
        let _ = writeln!(out, "| `{}` | {} |", n.name, n.basis);
    }
    let _ = writeln!(out, "\n## {}\n", w.leaks);
    for e in &source.known_leak {
        let _ = writeln!(
            out,
            "- **{}** ({}): {}",
            e.name,
            e.basis,
            meaning(lang, &e.meaning, &e.meaning_tr)
        );
    }
    let _ = writeln!(out, "\n## {}\n", w.rules);
    for e in &source.rule {
        let _ = writeln!(
            out,
            "- `{}`: {}",
            e.id,
            meaning(lang, &e.meaning, &e.meaning_tr)
        );
    }
    out
}

fn load(root: &Path) -> Result<Source, String> {
    toml::from_str(&read(&root.join(LIST))?).map_err(|e| format!("{LIST}: {e}"))
}

fn untranslated(source: &Source) -> Vec<String> {
    let columns = source
        .column
        .iter()
        .filter(|c| c.meaning_tr.trim().is_empty())
        .map(|c| c.name.clone());
    let entries = source
        .known_leak
        .iter()
        .chain(&source.rule)
        .filter(|e| e.meaning_tr.trim().is_empty())
        .map(|e| {
            if e.id.is_empty() {
                e.name.clone()
            } else {
                e.id.clone()
            }
        });
    columns.chain(entries).collect()
}

/// Writes both pages from the list.
pub(crate) fn generate(root: &Path) -> Result<(), String> {
    let source = load(root)?;
    let missing = untranslated(&source);
    if !missing.is_empty() {
        return Err(format!("{LIST}: no meaning_tr for {}", missing.join(", ")));
    }
    for (lang, page) in PAGES {
        let path = root.join(page);
        if let Some(dir) = path.parent() {
            std::fs::create_dir_all(dir).map_err(|e| format!("{page}: {e}"))?;
        }
        std::fs::write(&path, render(&source, lang)).map_err(|e| format!("{page}: {e}"))?;
        println!("wrote {page}");
    }
    Ok(())
}

pub(crate) fn check(root: &Path) -> Result<Vec<Violation>, String> {
    let source = load(root)?;
    let mut out: Vec<Violation> = untranslated(&source)
        .into_iter()
        .map(|name| v("SEC-30", LIST, format!("`{name}` has no meaning_tr")))
        .collect();
    for (lang, page) in PAGES {
        if read_opt(root, page)?.as_deref() != Some(render(&source, lang).as_str()) {
            out.push(v(
                "SEC-30",
                page,
                "differs from the plain-column list; run `cargo xtask security-design`".to_owned(),
            ));
        }
    }
    Ok(out)
}

#[cfg(test)]
mod tests {
    use super::*;

    // SEC-30
    #[test]
    fn sec_30_pages_list_every_plain_column_in_both_languages() {
        let source = load(&crate::workspace_root()).unwrap();
        assert_eq!(untranslated(&source), Vec::<String>::new());
        for (lang, _) in PAGES {
            let page = render(&source, lang);
            for c in &source.column {
                assert!(page.contains(&format!("| `{}` |", c.name)), "{}", c.name);
            }
            for n in &source.encrypted_only {
                assert!(page.contains(&format!("| `{}` |", n.name)), "{}", n.name);
            }
        }
    }
}
